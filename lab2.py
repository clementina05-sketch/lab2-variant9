def бинарный_поиск(список, искомый):
    """8. Реализовать бинарный поиск."""
    левый = 0
    правый = len(список) - 1

    while левый <= правый:
        средний = (левый + правый) // 2
        if список[средний] == искомый:
            return средний
        elif список[средний] < искомый:
            левый = средний + 1
        else:
            правый = средний - 1
    return -1


